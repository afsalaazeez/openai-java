    @Test
    @Tag("valid")
    void testConcurrentCompletionRequests() throws InterruptedException {
        int threadCount = 5;
        CountDownLatch latch = new CountDownLatch(threadCount);
        List<CompletionRequest> requests = new ArrayList<>();
        List<CompletionResult> expectedResults = new ArrayList<>();
        List<AtomicReference<CompletionResult>> results = new ArrayList<>();
        for (int i = 0; i < threadCount; i++) {
            CompletionRequest req = new CompletionRequest();
            req.setModel("text-davinci-003");
            req.setPrompt("Prompt " + i);
            requests.add(req);
            CompletionResult result = new CompletionResult();
            CompletionResult.Choice choice = new CompletionResult.Choice();
            choice.setText("Response " + i);
            result.setChoices(Collections.singletonList(choice));
            expectedResults.add(result);
            results.add(new AtomicReference<>());
        }
        for (int i = 0; i < threadCount; i++) {
            CompletionRequest req = requests.get(i);
            CompletionResult result = expectedResults.get(i);
            when(mockApi.createCompletion(req)).thenReturn(Single.just(result));
        }
        List<java.lang.Thread> threads = new ArrayList<>();
        for (int i = 0; i < threadCount; i++) {
            final int idx = i;
            java.lang.Thread t = new java.lang.Thread(() -> {
                CompletionResult r = service.createCompletion(requests.get(idx));
                results.get(idx).set(r);
                latch.countDown();
            });
            threads.add(t);
            t.start();
        }
        latch.await();
        for (int i = 0; i < threadCount; i++) {
            CompletionResult got = results.get(i).get();
            assertEquals("Response " + i, got.getChoices().get(0).getText());
        }
    }
